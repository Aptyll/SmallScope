// Checks that nothing the game ships sits there unused. Run on its own or as
// part of app/check-globals.js, the one lint:
//
//   node app/check-dead.js   # exit 0 clean, 1 with a report
//
// Dead code reads as live to the next person: they keep it working, document
// it and route around it. Delete it instead. Four kinds of thing are checked:
//
// NAMES. A top-level name is dead when it appears once in all of js/ (its own
// declaration) and nowhere in the pages, tools, bots or desktop code that
// reach into the game from outside (a headless runner calling G.name, a
// tool's page.evaluate, a string looked up by name). window.X exports are
// skipped (they are for code outside the game), and so are baked files' own
// names (a "GENERATED by" header). KEEP lists the few names kept on purpose
// with no caller today, each with its reason.
//
// SPRITES. A key put on SPRITES (`SPRITES.k = ...` or `Object.assign(SPRITES,
// { k })`, baked files included) is dead when nothing reads `SPRITES.k` and
// no dynamic lookup can hand it out. A dynamic read, `SPRITES[expr]`, must be
// listed in DYNAMIC with the keys it can take (read off the table that feeds
// it, so the list follows the code); an unlisted one fails, and so does an
// entry whose read is gone. A write through a key (`SPRITES.k.x = ...`) is not
// a read of it. DYNAMIC_PUT lists the keys registered by expression (the item
// icons), which are named by id, not checked here.
//
// SOUND CUES. A method on SFX (js/app/audio.js) is dead when nothing calls
// `SFX.name` and no string 'name' appears in js/ outside audio.js (a cue the
// sim raises goes by name: sfxAt('name', ...), sfxFor, sfxOwn, a table's
// cue). A string that only happens to share the name reads as a caller, so
// the check can miss a dead cue, never invent one. SFX_TOOLS lists the
// methods that are for a person at the console, each with where it is taught.
//
// SOUND FILES. A SAMPLES key is dead when audio.js never names it outside
// the table (smp('key'), or a ternary of two keys). Every file in audio/sfx/
// must be in a SAMPLES list, every listed file must exist, and
// js/baked/sfxdata.js must hold exactly audio/sfx/ (rerun app/bake-sfx.js).
// No packages.
'use strict';
const fs = require('fs');
const path = require('path');
const { tokenize, loadOrder, declarations } = require('./check-globals.js');

const ROOT = path.join(__dirname, '..');
const KEEP = {
  timeObj: 'the documented way to give a map object a clock (docs/dev/world.md)',
  MENU_BW: 'the title frame\'s layout, which the lobby and rooms screens line up with',
  MENU_BH: 'the title frame\'s layout, which the lobby and rooms screens line up with',
  MENU_PITCH: 'the title frame\'s layout, which the lobby and rooms screens line up with',
  MENU_Y0: 'the title frame\'s layout, which the lobby and rooms screens line up with',
  BAG_PAD: 'the HUD frame\'s padding, named in docs/dev/rendering',
  CIST_RI: 'the cistern wall\'s inner face, the pair of CIST_RO',
};
// code outside js/ that may reach a game global by name
const OUTSIDE = ['index.html', 'botlab.html', 'app', 'bots', 'desktop', 'docs/media'];
const baked = (src) => /GENERATED by/.test(src.split('\n', 12).join('\n'));

// ---- the tables the dynamic sprite reads are fed from ---------------------
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
// every 'value' of `field: 'value'` in a file
const strings = (rel, field) => () => [...read(rel).matchAll(new RegExp('\\b' + field + ":\\s*'([^']+)'", 'g'))].map((m) => m[1]);
// the keys of one object literal (no nested braces), `const NAME = { k: ... }` or `name: { k: ... }`
const keysOf = (rel, head) => () => {
  const m = read(rel).match(new RegExp(head + '\\s*\\{([^}]*)\\}'));
  return m ? [...m[1].matchAll(/([A-Za-z_$][\w$]*)\s*:/g)].map((k) => k[1]) : [];
};
const KINDS = keysOf('js/sim/wildlife.js', 'const ANIMAL_HP =');
// SPRITES[expr] reads: the file, the expression as written (spaces dropped), the keys it can take
const DYNAMIC = [
  { file: 'js/draw/bodies.js', expr: 'a.kind', keys: KINDS, why: 'a beast by its kind (ANIMAL_HP, js/sim/wildlife.js)' },
  { file: 'js/ui/wiki.js', expr: 'bs.kind', keys: KINDS, why: 'a wiki beast card by its kind (ANIMAL_HP)' },
  { file: 'js/sim/items.js', expr: "BUILD_ITEMS[id].icon||'item_'+id", keys: strings('js/sim/items.js', 'icon'), why: 'an item\'s named icon (BUILD_ITEMS), else item_<id>' },
  { file: 'js/draw/bodies.js', expr: 'T.spr', keys: strings('js/sim/robots.js', 'spr'), why: 'a soldier kind\'s team sets (SOLDIER_TYPES\' spr)' },
  { file: 'js/ui/loadout.js', expr: "kind+'_'+id", keys: () => [...read('js/sprites/loadout-icons.js').matchAll(/I\.((?:trick|calling)_\w+) =/g)].map((m) => m[1]), why: 'a pre-game pick\'s icon (loIcon)' },
  { file: 'js/draw/render.js', expr: 'key', keys: keysOf('js/sprites/items.js', 'itemAnim:'), why: 'an animated icon\'s live canvas (SPRITES.itemAnim)' },
];
// SPRITES[expr] = ...: keys registered by expression
const DYNAMIC_PUT = [
  { file: 'js/sprites/loadout-icons.js', expr: 'id', why: 'a pre-game pick\'s 16 px icon, read by loIcon (js/ui/loadout.js)' },
  { file: 'js/sprites/item-icons.js', expr: "'item_'+id", why: 'an item\'s 16 px icon, read by itemIcon (js/sim/items.js)' },
];
// SFX methods with no caller in the code, for a person at the console
const SFX_TOOLS = {
  debug: 'the sampled bank\'s state, docs/dev/checklists.md (verifying a change)',
  meter: 'the SOUNDS bus peak that proves a cue fires, docs/dev/checklists.md',
};

function walk(rel, out) {
  const p = path.join(ROOT, rel);
  if (!fs.existsSync(p)) return out;
  if (fs.statSync(p).isFile()) { out.push(p); return out; }
  for (const e of fs.readdirSync(p, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
    const r = rel + '/' + e.name;
    if (e.isDirectory()) walk(r, out);
    else if (/\.(js|mjs|cjs|html)$/.test(e.name)) out.push(path.join(ROOT, r));
  }
  return out;
}

// ---- token helpers ---------------------------------------------------------
const isP = (t, v) => t && t.t === 'p' && t.v === v;
const OPEN = { '(': ')', '[': ']', '{': '}' };
// the index of the bracket closing the one at k
function closer(toks, k) {
  const want = [OPEN[toks[k].v]];
  for (let j = k + 1; j < toks.length; j++) {
    const v = toks[j].t === 'p' ? toks[j].v : null;
    if (OPEN[v]) want.push(OPEN[v]);
    else if (v === want[want.length - 1]) { want.pop(); if (!want.length) return j; }
  }
  return toks.length - 1;
}
// a plain `=` at k (not ==, === or =>)
const assigns = (toks, k) => isP(toks[k], '=') && !isP(toks[k + 1], '=');
const text = (toks, a, b) => toks.slice(a, b).map((t) => (t.t === 'str' ? "'" + t.v + "'" : t.v)).join('');
// the keys of the object literal whose { is at k: [{ name, line }]
function literalKeys(toks, k) {
  const end = closer(toks, k), out = [];
  for (let j = k + 1; j < end; j++) {
    const t = toks[j];
    if (t.t === 'p' && OPEN[t.v]) { j = closer(toks, j); continue; }
    const head = isP(toks[j - 1], '{') || isP(toks[j - 1], ',');
    if (!head || (t.t !== 'id' && t.t !== 'str')) continue;
    const name = t.t === 'str' ? t.v : (t.v === 'get' || t.v === 'set') && toks[j + 1].t === 'id' ? toks[++j].v : t.v;
    out.push({ name, line: toks[j].line });
  }
  return { keys: out, end };
}

// ---- names -----------------------------------------------------------------
function deadNames(game, outside) {
  const uses = new Map(); // identifier -> times it appears in js/
  const bump = (v) => uses.set(v, (uses.get(v) || 0) + 1);
  const decls = [];
  for (const { file, src, toks } of game) {
    for (const t of toks) if (t.t === 'id') bump(t.v);
    for (const m of src.matchAll(/['"`]([A-Za-z_$][\w$]*)['"`]/g)) bump(m[1]); // a name looked up as a string
    if (baked(src)) continue;
    for (const d of declarations(src)) if (d.kind !== 'window') decls.push({ ...d, file });
  }
  const words = new Set(outside.match(/[A-Za-z_$][\w$]*/g));
  const problems = [];
  for (const d of decls) {
    if ((uses.get(d.name) || 0) > 1 || words.has(d.name) || KEEP[d.name]) continue;
    problems.push(`DEAD       ${d.name}: ${d.file}:${d.line} (${d.kind}) is never used - delete it, or add it to KEEP in app/check-dead.js with a reason`);
  }
  return problems;
}

// ---- sprites ---------------------------------------------------------------
function deadSprites(game, outside) {
  const put = new Map(), got = new Set(), problems = [];
  const dyn = DYNAMIC.map((d) => ({ ...d, seen: false })), dynPut = DYNAMIC_PUT.map((d) => ({ ...d, seen: false }));
  const register = (name, file, line) => { if (!put.has(name)) put.set(name, `${file}:${line}`); };
  for (const { file, toks } of game) {
    for (let i = 0; i < toks.length; i++) {
      const t = toks[i];
      if (t.t === 'id' && t.v === 'Object' && isP(toks[i + 1], '.') && toks[i + 2].v === 'assign' && isP(toks[i + 3], '(') &&
          toks[i + 4].v === 'SPRITES' && isP(toks[i + 5], ',') && isP(toks[i + 6], '{')) {
        const { keys } = literalKeys(toks, i + 6);
        for (const k of keys) register(k.name, file, k.line);
        i += 4; // on to SPRITES, which is not itself a read
        continue;
      }
      if (t.t !== 'id' || t.v !== 'SPRITES' || isP(toks[i - 1], '.')) continue;
      if (isP(toks[i + 1], '.') && toks[i + 2] && toks[i + 2].t === 'id') {
        const name = toks[i + 2].v, after = toks[i + 3];
        if (assigns(toks, i + 3)) { register(name, file, t.line); continue; }
        // a write through the key (SPRITES.k.x = or SPRITES.k[i] =) is not a read of it
        if (isP(after, '.') && toks[i + 4].t === 'id' && assigns(toks, i + 5)) continue;
        if (isP(after, '[') && assigns(toks, closer(toks, i + 3) + 1)) continue;
        got.add(name);
      } else if (isP(toks[i + 1], '[')) {
        const end = closer(toks, i + 1), expr = text(toks, i + 2, end);
        const list = assigns(toks, end + 1) ? dynPut : dyn;
        const hit = list.find((d) => d.file === file && d.expr === expr);
        if (hit) hit.seen = true;
        else problems.push(`SPRITE     SPRITES[${expr}]: ${file}:${t.line} is a dynamic ${list === dyn ? 'read' : 'registration'} - add it to ${list === dyn ? 'DYNAMIC' : 'DYNAMIC_PUT'} in app/check-dead.js with the keys it can take`);
      }
    }
  }
  for (const m of outside.matchAll(/\bSPRITES\.([A-Za-z_$][\w$]*)/g)) got.add(m[1]);
  for (const d of dyn.concat(dynPut)) {
    if (!d.seen) problems.push(`SPRITE     SPRITES[${d.expr}] is listed in app/check-dead.js for ${d.file} but is not there any more - drop the entry`);
  }
  for (const d of dyn) for (const k of d.keys()) got.add(k);
  for (const [name, at] of put) {
    if (!got.has(name)) problems.push(`SPRITE     SPRITES.${name}: ${at} is registered but nothing reads it - delete the sprite (and its grids and palette)`);
  }
  return problems;
}

// ---- sound cues and files ----------------------------------------------------
const AUDIO = 'js/app/audio.js', SFX_DIR = 'audio/sfx', SFX_DATA = 'js/baked/sfxdata.js';
function deadSounds(game, outside) {
  const problems = [];
  const audio = game.find((f) => f.file === AUDIO);
  if (!audio) return [`SOUND      ${AUDIO} is not loaded by index.html - check-dead cannot read SFX`];
  const toks = audio.toks;
  let methods = [], table = null;
  for (let i = 0; i < toks.length; i++) {
    if (toks[i].v === 'SFX' && isP(toks[i - 1], '.') && toks[i - 2].v === 'window' && assigns(toks, i + 1) && isP(toks[i + 2], '{')) methods = literalKeys(toks, i + 2).keys;
    if (toks[i].v === 'SAMPLES' && toks[i - 1].v === 'const' && isP(toks[i + 2], '{')) table = { at: i + 2, ...literalKeys(toks, i + 2) };
  }
  // cues: SFX.name anywhere, or the name as a string in js/ outside audio.js
  const called = new Set();
  for (const { file, toks: ft } of game) {
    for (let i = 0; i < ft.length; i++) {
      if (ft[i].v === 'SFX' && isP(ft[i + 1], '.') && ft[i + 2]) called.add(ft[i + 2].v);
      if (ft[i].t === 'str' && file !== AUDIO && ft[i].v) called.add(ft[i].v);
    }
  }
  for (const m of outside.matchAll(/\bSFX\.([A-Za-z_$][\w$]*)/g)) called.add(m[1]);
  for (const m of methods) {
    if (!called.has(m.name) && !SFX_TOOLS[m.name]) problems.push(`SOUND      SFX.${m.name}: ${AUDIO}:${m.line} has no caller - delete the cue, or add it to SFX_TOOLS in app/check-dead.js with where it is taught`);
  }
  for (const name in SFX_TOOLS) {
    if (!methods.some((m) => m.name === name)) problems.push(`SOUND      SFX_TOOLS.${name} in app/check-dead.js names no SFX method - drop the entry`);
  }
  if (!table) return problems.concat([`SOUND      const SAMPLES = { ... } not found in ${AUDIO}`]);
  // keys: named as a string in audio.js outside the table itself
  const named = new Set(), listed = new Set();
  toks.forEach((t, i) => {
    if (t.t !== 'str') return;
    if (i > table.at && i < table.end) listed.add(t.v); else named.add(t.v);
  });
  for (const k of table.keys) {
    if (!named.has(k.name)) problems.push(`SOUND      SAMPLES.${k.name}: ${AUDIO}:${k.line} is never played - delete the key and its files, then rerun node app/bake-sfx.js`);
  }
  const files = fs.readdirSync(path.join(ROOT, SFX_DIR)).filter((f) => /\.(mp3|ogg|wav)$/i.test(f));
  for (const f of files) {
    if (!listed.has(f)) problems.push(`SOUND      ${SFX_DIR}/${f} is in no SAMPLES list - delete it, then rerun node app/bake-sfx.js`);
  }
  for (const f of listed) {
    if (/\.(mp3|ogg|wav)$/i.test(f) && !files.includes(f)) problems.push(`SOUND      SAMPLES names ${f}, which is not in ${SFX_DIR}/`);
  }
  const bakedIn = new Set([...read(SFX_DATA).matchAll(/^("(?:[^"\\]|\\.)*"):"/gm)].map((m) => JSON.parse(m[1])));
  const stale = files.filter((f) => !bakedIn.has(f)).concat([...bakedIn].filter((f) => !files.includes(f)));
  if (stale.length) problems.push(`SOUND      ${SFX_DATA} is out of step with ${SFX_DIR}/ (${stale.join(', ')}) - rerun node app/bake-sfx.js`);
  return problems;
}

function check() {
  const game = [];
  for (const file of loadOrder()) {
    const p = path.join(ROOT, file);
    if (!fs.existsSync(p)) continue;
    const src = fs.readFileSync(p, 'utf8');
    game.push({ file, src, toks: tokenize(src) });
  }
  const outside = OUTSIDE.flatMap((r) => walk(r, []))
    .filter((p) => p !== __filename) // its own lists name them
    .map((p) => fs.readFileSync(p, 'utf8')).join('\n');
  return deadNames(game, outside).concat(deadSprites(game, outside), deadSounds(game, outside));
}

function main() {
  const problems = check();
  for (const p of problems) console.log(p);
  console.log(problems.length ? `\n${problems.length} unused thing(s)` : 'dead code ok');
  return problems.length ? 1 : 0;
}
module.exports = { check };
if (require.main === module) process.exit(main());
