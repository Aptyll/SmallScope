# Bakes the players' run and dodge roll into js/baked/motion.js as char grids.
#
#   python app/bake-player/bake.py     # needs numpy; rerun after changing the doll
#   python app/bake-player/preview.py out.png     # every frame on one sheet, to judge first
#
# The frames are not typed by hand: doll.py paints each hero look (bodies.py) as soft parts
# on a jointed doll, poses it (anim.py), turns it through the game's camera for each facing,
# shrinks it to the game's pixel and bands it into the player palette's letters. The idle and
# every other pose stay the hand-drawn grids (each hero's js/sprites/ file), which
# js/sprites/characters.js bakes beside these in every team paint. The grids this writes are
# the game's only copy.
import os, sys
import numpy as np
from doll import OX, OY, GROUND, grounded
from bodies import BODIES
import anim

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(HERE + '/../../js/baked/motion.js')
FACINGS = {'down': 90, 'up': -90, 'right': 0}           # left is right's mirror, in the game

_raw = {}


def raw(cls, kind, d):
    """the frames on the 24 x 24 work canvas, the body's root at (OX, OY)"""
    k = (cls, kind, d)
    if k in _raw: return _raw[k]
    body = BODIES[cls]; view = 'side' if d == 'right' else 'front'; h = FACINGS[d]
    if kind in ('run', 'hold'):
        pose = anim.run if kind == 'run' else anim.hold
        out = [body.render(pose(i, view), h) for i in range(anim.RUN_N)]
    else:
        out = []
        poses = anim.roll_poses(view)
        for i, (what, v) in enumerate(poses):
            if what == 'ball':
                g = body.render_ball(v, h)
            else:
                # the last, nearly standing frame is inked like the standing body (sides only);
                # the crouch, the dive and the deep squat like the compact roll shapes
                g = body.render(v, h, 'sides' if i == len(poses) - 1 else 'full')
            out.append(grounded(g))
    _raw[k] = out
    return out


# one box for every frame of every look, centred on the body's column so the mirrored left
# frames keep the feet where they were; CELL_X/CELL_Y is where the 16 x 16 cell's top-left
# sits inside it, which is how drawPlayer lines a frame up with the body
KINDS = ('run', 'hold', 'roll')
_all = [g for c in BODIES for kd in KINDS for d in FACINGS for g in raw(c, kd, d)]
_on = np.array([[[ch != '.' for ch in row] for row in g] for g in _all]).any(0)
_ys, _xs = np.nonzero(_on)
_half = int(max(OX - _xs.min(), _xs.max() + 1 - OX))
X0, X1, Y0, Y1 = int(OX) - _half, int(OX) + _half, int(_ys.min()), int(_ys.max()) + 1
CELL_X, CELL_Y = int(OX) - 8 - X0, int(OY) - 16 - Y0


def frames(cls, kind, d):
    return [[r[X0:X1] for r in g[Y0:Y1]] for g in raw(cls, kind, d)]


def js_rows(g, ind):
    return [f"{ind}'{r}'," for r in g]


def main():
    lines = ["'use strict';",
             "// The heroes' run cycle and dodge roll, every look, three facings (left is the",
             "// mirror of right). GENERATED by app/bake-player/bake.py from a painted doll of each",
             "// look (app/bake-player/bodies.py) - edit the doll and rebake, never these grids. Letters",
             "// are the player palette's (js/sprites/characters.js bakes them in every team paint).",
             "// RUN: eight frames, two steps, the right foot striking first. HOLD: the same legs with",
             "// the hands held in front (a drawn bow, a meal, a cast). ROLL: a crouch, a dive, the",
             "// tucked ball turning over once in 30 degree steps, a squat and a rise.",
             "(() => {",
             f"  // every frame is {X1 - X0} x {Y1 - Y0}; the 16 x 16 cell's top-left sits at (x, y) inside it",
             f"  const BOX = {{ w: {X1 - X0}, h: {Y1 - Y0}, x: {CELL_X}, y: {CELL_Y} }};",
             "  const GRIDS = {"]
    for cls in BODIES:
        lines.append(f"    {cls}: {{")
        for kind in KINDS:
            lines.append(f"      {kind}: {{")
            for d in FACINGS:
                lines.append(f"        {d}: [")
                for g in frames(cls, kind, d):
                    lines.append("          [")
                    lines += js_rows(g, '            ')
                    lines.append("          ],")
                lines.append("        ],")
            lines.append("      },")
        lines.append("    },")
    lines.append("  };")
    bob = ', '.join(str(b) for b in anim.BOB)
    starts = ', '.join(f'{s:.3f}'.rstrip('0').rstrip('.') if s else '0' for s in anim.roll_starts())
    hbob = ', '.join(str(b) for b in anim.HOLD_BOB)
    lines.append(f"  // the body's bob per frame of the run and of the held run, whole px up, for what rides")
    lines.append(f"  // the body (the held tool, the gear marks); and the share of DODGE_T at which each roll")
    lines.append(f"  // frame starts")
    lines.append(f"  SPR.motion = {{ BOX, GRIDS, RUN_BOB: [{bob}], HOLD_BOB: [{hbob}], ROLL_AT: [{starts}] }};")
    lines.append("})();")
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    low = [(c, k, d, i) for c in BODIES for k in KINDS for d in FACINGS
           for i, g in enumerate(raw(c, k, d)) if max(y for y, r in enumerate(g) if r.strip('.')) > GROUND]
    print('wrote', OUT, 'frame', X1 - X0, 'x', Y1 - Y0, 'cell at', (CELL_X, CELL_Y),
          '| below the ground row:', low or 'none')


if __name__ == '__main__':
    main()
