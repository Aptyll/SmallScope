# Bakes the GOLD PUMP (the generator) into js/baked/pump.js as char grids.
#
#   python3 app/bake-pump/bake.py     # needs numpy and pillow; rerun after changing pump.py
#
# pump.py paints every frame; this renders the three tiers' stroke cycles and
# the build-list icon with the team paint swapped for sentinel colours,
# crops every frame to one shared box, gives each colour a char and writes
# the grids. The team paint becomes k/K/e (fit, fitL, glow: teamBuildPal's
# letters), so js/baked/pump.js paints it inside onTeams. The grids this
# writes are the game's only copy.
import os, numpy as np
from pump import pump, icon, team, barrel_mouth, lint

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(HERE + '/../../js/baked/pump.js')
FRAMES = 8
SENT = ['#ff00f0', '#ff00f1', '#ff00f2']          # the team ramp, dark to light, as sentinels
team(SENT)
TEAMCH = {(255, 0, 0xf0): 'k', (255, 0, 0xf1): 'K', (255, 0, 0xf2): 'e'}

tiers = [[pump(t, f, FRAMES) for f in range(FRAMES)] for t in range(3)]
ic = icon()
for t in tiers:
    for f in t:
        l = lint(f, allowed=None)
        assert not l['clip'], 'a pump frame touches the 64 px edge'
on = np.any([f[..., 3] > 0 for t in tiers for f in t], axis=0)
ys, xs = np.nonzero(on)
x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1

chars = {}
POOL = [c for c in 'abcdfghijlmnopqrstuvwxyzABCDEFGHIJLMNOPQRSTUVWXYZ0123456789#$%&*+-=?@^~']
def ch(px):
    if px[3] == 0: return '.'
    rgb = tuple(int(v) for v in px[:3])
    if rgb in TEAMCH: return TEAMCH[rgb]
    if rgb not in chars: chars[rgb] = POOL[len(chars)]
    return chars[rgb]
def grid(f, box):
    a, b, c, d = box
    return [''.join(ch(f[y, x]) for x in range(a, b)) for y in range(c, d)]

G = [[grid(f, (x0, x1, y0, y1)) for f in t] for t in tiers]
I = grid(ic, (0, 16, 0, 16))
mouths = [(barrel_mouth(t)[0] - x0, barrel_mouth(t)[1] - y0) for t in range(3)]

out = ["'use strict';",
       "// THE GOLD PUMP: the generator, a pump jack on a 4x2 tile pad. GENERATED by",
       "// app/bake-pump/bake.py from the painter in app/bake-pump/pump.py - edit the",
       "// painter and rebake, never these grids. Per tier, one stroke as " + str(FRAMES) + " frames",
       "// (the crank turns, the beam nods, a glint runs down the pipe, the barrel's",
       "// gold bobs); the generator's draw picks the frame off its payout clock",
       "// (drawPump, js/draw/structs.js). k/K/e are the team paint (fit, fitL,",
       "// glow), baked inside onTeams; frame 0 of each tier is the building's",
       "// still sprite (structSprite) and ICON its build-list glyph.",
       "(() => {",
       "  const { bake, onTeams, TEAM_SKINS, teamBuildPal } = SPR;",
       "  const BASE = { " + ', '.join(f"'{c}': '#{r:02x}{g:02x}{b:02x}'" for (r, g, b), c in chars.items()) + ", '.': null };",
       "  const TIERS = ["]
for t in G:
    out.append("    [")
    for f in t:
        out.append("      [")
        out += [f"        '{r}'," for r in f]
        out.append("      ],")
    out.append("    ],")
out += ["  ];",
        "  const ICON = ["]
out += [f"    '{r}'," for r in I]
out += ["  ];",
        "  // the barrel's mouth in each tier's frame, px from its top-left: the payout's coin hops from here",
        "  const MOUTH = " + str([list(map(int, m)) for m in mouths]) + ";",
        "  onTeams(() => TEAM_SKINS.forEach((t, i) => {",
        "    const pal = teamBuildPal(BASE, t), set = SPRITES.teamBuild[i];",
        "    set.pumpAnim = TIERS.map((fr) => fr.map((g) => bake(g, pal)));",
        "    set.generator = set.pumpAnim.map((fr) => fr[0]);",
        "    set.icon.generator = bake(ICON, pal);",
        "    if (i === 0) SPRITES.generator = set.generator;",
        "  }));",
        "  SPRITES.pumpMouth = MOUTH;",
        "})();",
        ""]
open(OUT, 'w', newline='\n').write('\n'.join(out))
print(OUT, 'box', (x0, x1, y0, y1), 'colours', len(chars) + 3, 'lines', len(out))
