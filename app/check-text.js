// Checks the text table (TEXT, js/app/text.js). Run on its own or as part of
// app/check-globals.js, the one lint:
//
//   node app/check-text.js           # exit 0 clean, 1 with a report
//   node app/check-text.js --loose   # the loose words left in every game file, by file
//
// It fails:
//   - a tr('key') whose key TEXT does not have (it would print the key);
//   - a TEXT key no game file names (a dead word, the table's dead code);
//   - a value with a character the pixel font lacks (GLYPHS, js/app/font.js),
//     which prints as '?', or with lowercase (the game's text is capitals);
//   - a loose word in a MOVED file: a file whose words have all moved into
//     the table may not grow a new one, so the table stays the one place.
//
// A key counts as named wherever its exact text sits in a quoted string, so
// a key kept in a data table (`word: 'recap.attacks'`) and passed to tr()
// later counts too. A loose word is a quoted string with two capitals in a
// row and no lowercase (a colour, an id with an underscore, a lone mark
// are not words). No packages.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { tokenize, loadOrder } = require('./check-globals.js');

const ROOT = path.join(__dirname, '..');
const TEXT_FILE = 'js/app/text.js';
// the files whose every word is in the table. A file joins once its last
// loose word moves in; it never leaves.
const MOVED = [
  'js/ui/screens.js',
  'js/ui/endscreens.js',
  'js/ui/recap.js',
  'js/ui/lobby.js',
];

function readText() {
  const src = fs.readFileSync(path.join(ROOT, TEXT_FILE), 'utf8');
  return vm.runInNewContext(src + '\n;TEXT', {});
}
function readGlyphs() {
  const src = fs.readFileSync(path.join(ROOT, 'js/app/font.js'), 'utf8');
  const set = new Set();
  const re = /^\s*(?:'(\\.|[^'])'|"([^"])"):\s*'[01]{15}'/gm;
  let m;
  while ((m = re.exec(src))) set.add(m[1] !== undefined ? m[1].replace(/^\\/, '') : m[2]);
  return set;
}
const unescape = (v) => v.replace(/\\(.)/g, '$1');
const looseWord = (v) => /[A-Z]{2}/.test(v) && !/[a-z]/.test(v) && !/^#/.test(v) && !/_/.test(v);

function check() {
  const problems = [];
  const TEXT = readText();
  const keys = new Set(Object.keys(TEXT));
  const glyphs = readGlyphs();
  for (const k of keys) {
    const v = TEXT[k];
    if (!/^[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9]+)+$/.test(k)) problems.push(`TEXT KEY   '${k}': keys are screen.thing, lowercase first`);
    const bad = [...new Set([...v.replace(/\{\w+\}/g, '')].filter((c) => !glyphs.has(c)))];
    if (bad.length) problems.push(`TEXT GLYPH '${k}': ${bad.map((c) => JSON.stringify(c)).join(' ')} not in the pixel font (prints as ?)`);
  }
  const used = new Set();
  const loose = [];
  for (const file of loadOrder()) {
    if (file === TEXT_FILE || !file.startsWith('js/')) continue;
    const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
    if (/GENERATED by/.test(src.split('\n', 12).join('\n'))) continue;
    const toks = tokenize(src);
    for (let i = 0; i < toks.length; i++) {
      const t = toks[i];
      if (t.t !== 'str') continue;
      const v = unescape(t.v);
      if (keys.has(v)) used.add(v);
      const call = toks[i - 2] && toks[i - 2].t === 'id' && toks[i - 2].v === 'tr' && toks[i - 1].v === '(';
      if (call && v && !keys.has(v)) problems.push(`TEXT MISS  ${file}:${t.line} tr('${v}'): no such key in ${TEXT_FILE}`);
      if (looseWord(v)) loose.push({ file, line: t.line, v });
    }
  }
  for (const k of keys) if (!used.has(k)) problems.push(`TEXT DEAD  '${k}': no game file names it - delete it`);
  for (const w of loose) if (MOVED.includes(w.file)) problems.push(`TEXT LOOSE ${w.file}:${w.line} '${w.v}': this file's words live in ${TEXT_FILE} - add a key`);
  return { problems, loose };
}

function main() {
  const { problems, loose } = check();
  if (process.argv.includes('--loose')) {
    const by = {};
    for (const w of loose) by[w.file] = (by[w.file] || 0) + 1;
    for (const [f, n] of Object.entries(by).sort((a, b) => b[1] - a[1])) console.log(String(n).padStart(5), f);
    console.log(String(loose.length).padStart(5), 'loose words in all');
  }
  for (const p of problems) console.log(p);
  if (!problems.length) console.log('text ok');
  return problems.length ? 1 : 0;
}
module.exports = { check: () => check().problems };
if (require.main === module) process.exit(main());
