// Bakes the pictures in docs/media/notes/ into js/notesart.js, so a patch note can
// show the art it shipped (or the concept it sketched). A note names its picture by
// file name as its third field: ['0.391', 'TEXT.', 'winter-flowers'].
// Each picture goes in as a PNG data URL with its size: the game opens off the disk
// with no server, and a data: URL taints no canvas (an <img> read off file:// does).
// Keep them small and at 1x: the notes screen scales a picture up by whole pixels.
//
//   node app/bake-notes-art.js     # rerun after adding or changing a picture
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'docs', 'media', 'notes');
const OUT = path.join(ROOT, 'js', 'notesart.js');
const MAX_BYTES = 24 * 1024; // a picture this big is not a 1x pixel strip

const out = {};
for (const f of fs.readdirSync(SRC).filter((f) => f.endsWith('.png')).sort()) {
  const buf = fs.readFileSync(path.join(SRC, f));
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error(f + ' is not a PNG');
  if (buf.length > MAX_BYTES) throw new Error(`${f} is ${buf.length} bytes: bake the 1x art, not a sheet`);
  out[f.slice(0, -4)] = { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20), src: 'data:image/png;base64,' + buf.toString('base64') };
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': { w: ${v.w}, h: ${v.h}, src: '${v.src}' },`).join('\n');
fs.writeFileSync(OUT, `// GENERATED by app/bake-notes-art.js from docs/media/notes/ - do not edit by hand.\n// The pictures patch notes show, by name: PATCH_NOTES' third field (js/ui/menu.js).\nwindow.NOTES_ART = {\n${body}\n};\n`);
console.log('baked', Object.keys(out).length, 'pictures ->', path.relative(ROOT, OUT));
