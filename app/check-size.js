// Checks that no game file or function grows too big to read whole. Run on
// its own or as part of app/check-globals.js, the one lint:
//
//   node app/check-size.js            # exit 0 clean, 1 with a report
//   node app/check-size.js --top 20   # the 20 biggest files and functions
//   node app/check-size.js --tighten  # lower app/size-baseline.json to today's sizes
//   node app/check-size.js --init     # rewrite it with every giant there is (the check's first day only)
//
// Size is CODE lines: a line with a name or an operator on it. Blank,
// comment-only and data-only lines (a pixel-grid row, a table of numbers) are
// free, so explaining code, or drawing in it, never costs anything. A function counts its
// OWN lines, not the functions nested inside it (those count on their own),
// so a file wrapped in one (() => { ... })() is not one giant function.
//
// A file over FILE_MAX or a function over FN_MAX fails, unless
// app/size-baseline.json lists it: the giants that were already there when
// the check came in. A listed one may shrink but never grow past its number.
// --tighten writes the smaller number back (and drops what is now under the
// limit); it never raises one. Raising one by hand is a choice a reviewer
// sees in the diff. A baked file (a "GENERATED by" header) is art or data,
// not code, and is never measured.
//
// Functions are named by where they sit: `aiThink`, `outer.inner` for one
// nested in another, `<anon>` for an unnamed one, `#2` on a repeat. No packages.
'use strict';
const fs = require('fs');
const path = require('path');
const { tokenize, loadOrder } = require('./check-globals.js');

const ROOT = path.join(__dirname, '..');
const BASELINE = path.join(__dirname, 'size-baseline.json');
const FILE_MAX = 1000; // code lines in one file
const FN_MAX = 120;    // a function's own code lines

const DATA_PUNCT = new Set([',', '[', ']', '{', '}', '(', ')', ';', ':', '-', '.']);
const baked = (src) => /GENERATED by/.test(src.split('\n', 12).join('\n'));

// a call or a statement head, never a method: `if (x) {`, `while (y) {`
const NOT_METHOD = new Set(['if', 'for', 'while', 'switch', 'catch', 'with', 'function', 'return', 'typeof', 'await', 'yield']);

// the index of the bracket matching toks[k] (an opener), scanning forward
function closeOf(toks, k) {
  let d = 0;
  for (; k < toks.length; k++) {
    const v = toks[k].t === 'p' ? toks[k].v : null;
    if (v === '(' || v === '[' || v === '{') d++;
    else if (v === ')' || v === ']' || v === '}') { if (--d === 0) return k; }
  }
  return toks.length - 1;
}
// the index of the opener matching toks[k] (a closer), scanning back
function openOf(toks, k) {
  let d = 0;
  for (; k >= 0; k--) {
    const v = toks[k].t === 'p' ? toks[k].v : null;
    if (v === ')' || v === ']' || v === '}') d++;
    else if (v === '(' || v === '[' || v === '{') { if (--d === 0) return k; }
  }
  return 0;
}
// the name an expression at toks[k] is given: `x = `, `a.x = `, `x: `
function nameBefore(toks, k) {
  const a = toks[k - 1], b = toks[k - 2];
  if (a && (a.v === '=' || a.v === ':') && b && b.t === 'id') return b.v;
  return null;
}

// every function with a block body in one file: { name, line, body: [open, close] }
function functions(toks) {
  const out = [];
  for (let k = 0; k < toks.length; k++) {
    const t = toks[k];
    if (t.t === 'id' && t.v === 'function' && !(toks[k - 1] && toks[k - 1].v === '.')) {
      let j = k + 1;
      if (toks[j] && toks[j].v === '*') j++;
      let name = null;
      if (toks[j] && toks[j].t === 'id') name = toks[j++].v;
      if (!toks[j] || toks[j].v !== '(') continue;
      const open = closeOf(toks, j) + 1;
      if (!toks[open] || toks[open].v !== '{') continue;
      const at = toks[k - 1] && toks[k - 1].v === 'async' ? k - 1 : k;
      out.push({ name: name || nameBefore(toks, at), line: t.line, body: [open, closeOf(toks, open)] });
    } else if (t.v === '=>' && t.t === 'p') {
      if (!toks[k + 1] || toks[k + 1].v !== '{') continue; // an expression body: one expression
      let start = k - 1;
      if (toks[start] && toks[start].v === ')') start = openOf(toks, start);
      if (toks[start - 1] && toks[start - 1].v === 'async') start--;
      out.push({ name: nameBefore(toks, start), line: toks[start].line, body: [k + 1, closeOf(toks, k + 1)] });
    } else if (t.t === 'id' && !NOT_METHOD.has(t.v) && toks[k + 1] && toks[k + 1].v === '(' && !(toks[k - 1] && toks[k - 1].v === 'function')) {
      // a method in a class or an object literal: `name(args) {` (no call is followed by a block)
      const close = closeOf(toks, k + 1);
      if (!toks[close + 1] || toks[close + 1].v !== '{') continue;
      const p = toks[k - 1];
      if (p && p.v === '.') continue;
      out.push({ name: t.v, line: t.line, body: [close + 1, closeOf(toks, close + 1)] });
    }
  }
  return out;
}

// { code, fns: [{ key, line, size }] } for one file's source
function measure(src) {
  const toks = tokenize(src);
  // a line of only strings, numbers and brackets is data (a pixel grid row, a
  // table), free like a comment: only a name or an operator makes a line code
  const live = new Set();
  for (const t of toks) if (t.t === 'id' || (t.t === 'p' && !DATA_PUNCT.has(t.v))) live.add(t.line);
  const code = live.size;
  const fns = functions(toks).sort((a, b) => a.body[0] - b.body[0]);
  // each token belongs to the innermost function body around it
  const own = fns.map(() => new Set());
  const stack = [];
  let f = 0;
  for (let k = 0; k < toks.length; k++) {
    while (stack.length && k > fns[stack[stack.length - 1]].body[1]) stack.pop();
    while (f < fns.length && fns[f].body[0] === k) stack.push(f++);
    if (stack.length && live.has(toks[k].line)) own[stack[stack.length - 1]].add(toks[k].line);
  }
  // paths: enclosing named functions, outermost first
  const seen = new Map(), out = [];
  const chain = [];
  fns.forEach((fn, i) => {
    while (chain.length && fns[chain[chain.length - 1]].body[1] < fn.body[0]) chain.pop();
    const parts = chain.map((c) => fns[c].name || '<anon>').concat(fn.name || '<anon>');
    chain.push(i);
    let key = parts.join('.');
    const n = (seen.get(key) || 0) + 1;
    seen.set(key, n);
    if (n > 1) key += '#' + n;
    out.push({ key, line: fn.line, size: own[i].size });
  });
  return { code, fns: out };
}

// every measured file and function: [{ id, file, line, size, max }]
function sizes() {
  const rows = [];
  for (const f of loadOrder()) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const src = fs.readFileSync(p, 'utf8');
    if (baked(src)) continue;
    const m = measure(src);
    rows.push({ id: f, file: f, line: 1, size: m.code, max: FILE_MAX });
    for (const fn of m.fns) rows.push({ id: f + ' ' + fn.key, file: f, line: fn.line, size: fn.size, max: FN_MAX });
  }
  return rows;
}

// a giant's allowance: its own entry, or the entry it had in another file
// before a split moved it (a named function keeps its name when it moves)
function allowance(base, r) {
  if (base[r.id] !== undefined) return base[r.id];
  const fn = r.id.split(' ')[1];
  if (!fn || fn.startsWith('<anon>')) return undefined;
  for (const k of Object.keys(base)) if (k.split(' ')[1] === fn) return base[k];
  return undefined;
}

function readBaseline() {
  try { return JSON.parse(fs.readFileSync(BASELINE, 'utf8')); } catch (e) { return {}; }
}
function writeBaseline(b) {
  const keys = Object.keys(b).sort();
  const body = keys.map((k) => `  ${JSON.stringify(k)}: ${b[k]}`).join(',\n');
  fs.writeFileSync(BASELINE, '{\n' + body + '\n}\n');
}

// the problems, as lines; [] when clean
function check() {
  const base = readBaseline(), problems = [];
  for (const r of sizes()) {
    if (r.size <= r.max) continue;
    const what = r.id.includes(' ') ? `function ${r.id.split(' ')[1]} (${r.file}:${r.line})` : `file ${r.file}`;
    const allowed = allowance(base, r);
    if (allowed === undefined) problems.push(`TOO BIG    ${what}: ${r.size} code lines, the limit is ${r.max}`);
    else if (r.size > allowed) problems.push(`GREW       ${what}: ${r.size} code lines, was ${allowed} (already over ${r.max}: move the new code out)`);
  }
  return problems;
}

function main() {
  const argv = process.argv;
  if (argv.includes('--top')) {
    const n = +argv[argv.indexOf('--top') + 1] || 20, rows = sizes();
    const show = (list) => list.sort((a, b) => b.size - a.size).slice(0, n)
      .forEach((r) => console.log(String(r.size).padStart(6) + '  ' + r.id + (r.id.includes(' ') ? `  (${r.file}:${r.line})` : '')));
    console.log('files'); show(rows.filter((r) => r.max === FILE_MAX));
    console.log('functions'); show(rows.filter((r) => r.max === FN_MAX));
    return 0;
  }
  if (argv.includes('--tighten') || argv.includes('--init')) {
    // --init writes every giant there is today; only for bringing the check in
    const base = argv.includes('--init') ? null : readBaseline(), next = {};
    for (const r of sizes()) {
      if (r.size <= r.max) continue;
      if (!base) next[r.id] = r.size;
      else if (allowance(base, r) !== undefined) next[r.id] = Math.min(allowance(base, r), r.size);
    }
    writeBaseline(next);
    console.log(`size baseline: ${Object.keys(next).length} entries`);
    return 0;
  }
  const problems = check();
  if (!problems.length) { console.log('sizes ok'); return 0; }
  for (const p of problems) console.log(p);
  console.log(`\n${problems.length} size problem(s): split the file along its sections, or the function into named steps`);
  return 1;
}

module.exports = { check, measure };
if (require.main === module) process.exit(main());
