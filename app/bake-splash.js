// Bakes the champ select's splash art in docs/media/splash/ into js/baked/splash.js, so the
// big picture after you lock in and the skin strip under it work with the game opened off the
// disk: a data: URL taints no canvas (an <img> read off file:// does).
//
// One pair per look, named by the hero's skin slot and the look's id (CLASSES[h].skinSlot and
// the row id in ARM_SKINS, FORT_SKINS, BELLA_SKINS...):
//   <slot>-<id>.png        the splash, SPLASH_W x SPLASH_H (288x160) at 1x
//   <slot>-<id>-thumb.png  its strip thumbnail, SKIN_THUMB_W x SKIN_THUMB_H (48x28): a crop
//                          or its own drawing, never the splash shrunk
// A look with no files keeps the stand-in (the model on the night, js/ui/select.js).
//
//   node app/bake-splash.js     # rerun after adding or changing a picture
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'docs', 'media', 'splash');
const OUT = path.join(ROOT, 'js', 'baked', 'splash.js');
const SPLASH = [288, 160], THUMB = [48, 28]; // SPLASH_W/H and SKIN_THUMB_W/H, js/ui/select.js

const out = {};
for (const f of fs.readdirSync(SRC).filter((f) => f.endsWith('.png')).sort()) {
  const buf = fs.readFileSync(path.join(SRC, f));
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error(f + ' is not a PNG');
  const w = buf.readUInt32BE(16), h = buf.readUInt32BE(20), name = f.slice(0, -4);
  const want = name.endsWith('-thumb') ? THUMB : SPLASH;
  if (w !== want[0] || h !== want[1]) throw new Error(`${f} is ${w}x${h}, not ${want[0]}x${want[1]}`);
  if (!/^[a-z0-9]+-[a-z0-9]+(-thumb)?$/.test(name)) throw new Error(`${f}: name it <slot>-<id>.png or <slot>-<id>-thumb.png`);
  out[name] = 'data:image/png;base64,' + buf.toString('base64');
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
fs.writeFileSync(OUT, `// GENERATED by app/bake-splash.js from docs/media/splash/ - do not edit by hand.\n// The champ select's splash art and skin thumbnails, by '<slot>-<id>' and '<slot>-<id>-thumb' (js/ui/select.js).\nwindow.SPLASH_ART = {\n${body}\n};\n`);
console.log('baked', Object.keys(out).length, 'pictures ->', path.relative(ROOT, OUT));
