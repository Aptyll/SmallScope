function drawPopSlab(panel, rise) {
  const a = ctx.globalAlpha, py = panel.y + rise;
  ctx.fillStyle = 'rgba(4,6,18,' + (0.62 * a).toFixed(3) + ')';
  ctx.globalAlpha = 1; ctx.fillRect(0, 0, VIEW_W, VIEW_H); ctx.globalAlpha = a;
  ctx.fillStyle = 'rgba(4,6,18,0.55)'; chamRect(panel.x + 3, py + 3, panel.w, panel.h);
  ctx.fillStyle = '#0a0e23'; chamRect(panel.x, py, panel.w, panel.h);
  ctx.fillStyle = '#10173a'; chamRect(panel.x + 1, py + 1, panel.w - 2, panel.h - 2);
  ctx.fillStyle = '#35426e';
  ctx.fillRect(panel.x + 2, py + 1, panel.w - 4, 1); ctx.fillRect(panel.x + 1, py + 2, 1, panel.h - 4);
  ctx.fillStyle = '#080c1c';
  ctx.fillRect(panel.x + 2, py + panel.h - 2, panel.w - 4, 1); ctx.fillRect(panel.x + panel.w - 2, py + 2, 1, panel.h - 4);
}
function drawPopX(xr, rise, hot) {
  ctx.fillStyle = hot ? '#8fa0c8' : '#35426e';
  ctx.fillRect(xr.x, xr.y + rise, xr.w, xr.h);
  ctx.fillStyle = '#0f1632';
  ctx.fillRect(xr.x + 1, xr.y + rise + 1, xr.w - 2, xr.h - 2);
  ctx.fillStyle = hot ? '#f4f7ff' : '#8fa8d0';
  for (let k = 0; k < 4; k++) {
    ctx.fillRect(xr.x + 3 + k, xr.y + rise + 3 + k, 1, 1);
    ctx.fillRect(xr.x + xr.w - 4 - k, xr.y + rise + 3 + k, 1, 1);
  }
}
// a pop-up's inert hit answers: 'x', 'panel' (the slab swallows the press)
// or null (outside - a click there closes)
function popFrameHit(panel, xr) {
  if (mouse.x >= xr.x - 3 && mouse.x < xr.x + xr.w + 3 && mouse.y >= xr.y - 3 && mouse.y < xr.y + xr.h + 3) return 'x';
  if (mouse.x >= panel.x && mouse.x < panel.x + panel.w && mouse.y >= panel.y && mouse.y < panel.y + panel.h) return 'panel';
  return null;
}

// ---- drawing the title screen ---------------------------------------------
function renderTitle(now) {
  const m = state.menu;
  // leaving: 0 while the menu is up, 0->1 over the intro
  const outQ = state.intro > 0 ? 1 - state.intro / INTRO_T : 0;
  const tintA = 0.55 * (1 - easeOut(outQ / 0.45));
  if (tintA > 0.005) drawTitleBackdrop(tintA);
  const out = easeOut(outQ / 0.22);           // menu chrome drops away first
  const sc = easeInOut(m.screenT);             // the lobby cross-fade
  const tc = easeInOut(m.wikiT);               // ...and the wiki's own
  const nc = easeInOut(m.notesT);              // ...and the patch notes'
  const kc = easeInOut(m.charT);               // ...and the profile card's
  const rc = easeInOut(m.roomsT);              // ...and the party lobby's
  const bc = easeInOut(m.skinT);               // ...and the skins screen's
  const pan = Math.max(m.panel ? easeOut(m.panelT) : 0, sc, tc, nc, kc, rc, bc); // chrome ducks under a panel or any full screen
  const { toy, rects } = menuLayout();
  const cx = Math.round(VIEW_W / 2);
  const chromeA = (1 - out) * (1 - pan);

  // logo: drops in at boot, lifts away on play
  const logoIn = easeOut(m.t / 0.6);
  const ly = Math.round(LOGO_Y - (1 - logoIn) * 30 - out * 40); // still at rest: no bob
  const logoA = logoIn * (1 - out) * (1 - pan) * (1 - sc);
  const logoOk = LOGO_IMG.complete && LOGO_IMG.naturalWidth > 0;
  const lw = logoOk ? LOGO_IMG.naturalWidth : pixelTextWidth('SOFTFALL', 4);
  const lh = logoOk ? LOGO_IMG.naturalHeight : 28;
  const lx = Math.round((VIEW_W - lw) / 2);
  // a pulsing cold glow behind the letters: the picture's own cyan halo
  ctx.globalCompositeOperation = 'lighter';
  const pulse = 0.8 + 0.2 * Math.sin(now * 2.2);
  const gr = 96, gy = ly + (lh >> 1);
  const grd = ctx.createRadialGradient(cx, gy, 2, cx, gy, gr);
  grd.addColorStop(0, 'rgba(110,200,255,' + (0.22 * logoA * pulse).toFixed(3) + ')');
  grd.addColorStop(0.5, 'rgba(80,150,255,' + (0.07 * logoA * pulse).toFixed(3) + ')');
  grd.addColorStop(1, 'rgba(60,120,255,0)');
  ctx.fillStyle = grd; ctx.fillRect(cx - gr, gy - gr, gr * 2, gr * 2);
  ctx.globalCompositeOperation = 'source-over';
  ctx.globalAlpha = logoA;
  if (logoOk) ctx.drawImage(LOGO_IMG, lx, ly);
  else drawPixelTextShadow(ctx, 'SOFTFALL', lx, ly, '#ffd95c', '#3c2a1e', 4); // the word, until the picture decodes
  ctx.globalAlpha = 1;

  // items: plain words that fade in staggered, sink away on play and duck
  // under a panel; the picked one warms to gold and lifts a px, a press sinks it
  for (let i = 0; i < rects.length; i++) {
    const r = rects[i];
    const inT = easeOut((m.t - 0.25 - i * 0.12) / 0.45);
    const a = inT * (1 - out) * (1 - pan);
    if (a <= 0.005) continue;
    const hv = m.hover[i];
    const pressed = m.sel === i && (m.pressT > 0 || (mouse.down && menuHit() === i));
    const y = r.y + 2 + Math.round((1 - inT) * 8) + Math.round(out * 25) - Math.round(hv) + (pressed ? 1 : 0);
    ctx.globalAlpha = a;
    drawPixelTextOutline(ctx, MENU_ITEMS[i], r.x + 4, y, hv > 0.5 ? '#ffd95c' : '#f4f7ff', 'rgba(8,12,28,0.9)', MENU_TXT_SCALE);
    ctx.globalAlpha = 1;
  }

  // footer: the two corner tags ride the same fade; no gold rule under them
  const fin = easeOut((m.t - 0.9) / 0.5) * (1 - out) * (1 - pan);
  if (fin > 0.005) {
    ctx.globalAlpha = fin;
    const pr = patchTagRect();
    const phot = !m.panel && overPatchTag();
    drawPixelTextShadow(ctx, PATCH_TXT, pr.x, pr.y, phot ? '#ffd95c' : '#5a6690', 'rgba(15,22,50,0.9)');
    if (phot) { ctx.fillStyle = '#c89a3c'; ctx.fillRect(pr.x, pr.y + 7, pr.w, 1); }
    drawProfileTag(); // your name and its quill, opposite corner: the way to the profile card
    drawCoinTag();    // the purse, top-right: the way into the skins screen
    ctx.globalAlpha = 1;
  }

  // the lobby stays fully lit under the hero pop-up, which rides an ease of
  // its own (popT)
  const gc = easeInOut(state.menu.popT);
  if (sc > 0.005) renderLobby(now, sc * (1 - out));
  if (sc > 0.005 && gc > 0.005) {
    const pa = sc * (1 - out) * gc;
    if (m.pop === 'hero') renderHero(now, pa);
  }
  if (nc > 0.005) renderNotes(now, nc * (1 - out));
  if (tc > 0.005) renderWiki(now, tc * (1 - out));
  if (nc + tc > 0.005) drawPageTabs(Math.min(1, nc + tc) * (1 - out)); // one row over both, so a switch never fades it
  if (kc > 0.005) renderProfileCard(now, kc * (1 - out));
  if (rc > 0.005) renderRoom(now, rc * (1 - out));
  if (bc > 0.005) renderSkins(now, bc * (1 - out));
  drawFriendCard(); // a Steam friend's invite, over whichever screen (js/ui/friends.js)

  // sub-panels slide up from the bottom edge over the still-visible world
  if (m.panel) {
    const slide = Math.round((1 - easeOut(m.panelT)) * (VIEW_H - SET_Y + 6));
    if (m.panel === 'settings') renderSettings(now, { bare: true, slide });
    else ctx.drawImage(helpPanelCv, SET_X, SET_Y + slide);
  }
}
