  ctx.fillStyle = picked ? '#1a2142' : '#0f1632';
  ctx.fillRect(x + 1, y + 1, w - 2, h - 2);
  ctx.globalAlpha *= picked || hot ? 1 : 0.75;
  ctx.drawImage(gearIcon32(slot, v), x + 3, y + 3);
