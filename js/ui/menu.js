      ctx.fillRect(x, y + 2, 1, h - 4); ctx.fillRect(x + w - 1, y + 2, 1, h - 4);
      const sw = ((now * 26) % (w + h + 24)) - h - 12;
      ctx.globalAlpha = a0 * cold * 0.3;
      ctx.fillStyle = '#ffffff';
