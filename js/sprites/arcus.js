// the eight headings off the three set ones: `d` art px a world px (the grips and hands stay world px)
function arcusBowAim(E, SE, S, pal, d) {
  // the bow hand from the chest, by step: [level, down, up] px (a diagonal takes three quarters)
  const REACH = [[7, 5, 2], [10, 5, 2], [10, 5, 2]];
  const out = [[], [], [], [], [], [], [], []];
  const tag = (c) => { if (d > 1) c.dens = d; return c; };
  for (let f = 0; f < 3; f++) {
    const e = SPR.bake(E[f], pal), s = SPR.bake(S[f], pal), dd = SPR.bake(SE[f], pal);
    const ew = e.width / d, dw = dd.width / d, dh = dd.height / d, sh = s.height / d; // world px
    const eg = [8, 6], sg = [7, 4], dg = [8, 8]; // the stave's middle on each grid
    const row = [
      [e, eg], [dd, dg], [s, sg], [SPR.flipH(dd), [dw - 1 - dg[0], dg[1]]],
      [SPR.flipH(e), [ew - 1 - eg[0], eg[1]]], [SPR.flipV(SPR.flipH(dd)), [dw - 1 - dg[0], dh - 1 - dg[1]]],
      [SPR.flipV(s), [sg[0], sh - 1 - sg[1]]], [SPR.flipV(dd), [dg[0], dh - 1 - dg[1]]],
    ];
    row.forEach(([img, grip], h) => {
      const q = h * Math.PI / 4, c = Math.round(Math.cos(q)), sn = Math.round(Math.sin(q)), k = c && sn ? 0.75 : 1;
      // the chest's middle is between two columns: a hand to the left reaches one more, so left mirrors right
      out[h][f] = { img: tag(img), grip, hand: [Math.round(c * REACH[f][0] * k) - (c < 0 ? 1 : 0), Math.round(sn * REACH[f][sn > 0 ? 1 : 2] * k)] };
    });
  }
  return out;
}
